# Genera el filtro Zadark HD para mGBA (GLSL) y RetroArch (slang) desde un mismo código.
#   python3 shaders/tools/gen_shaders.py
# Pasadas:
#   1) zhd-xbr : xBR-lv3 (Hyllian, MIT) x4 + mezcla con el píxel original (BORDES) + color (VIVO)
#   2) zhd-cas : nitidez CAS (AMD FidelityFX, MIT) + resplandor suave
#   3) zhd-tex : textura diagonal a resolución de pantalla (idea del filtro de TV de PCSX2)
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
XBR_FS = os.path.join(HERE, 'xbr-lv3.fs')   # copia del xbr.fs de mGBA (Hyllian, MIT)
XBR_VS = os.path.join(HERE, 'xbr-lv3.vs')

HEADER = '''/*
   Zadark HD - filtro de Zadark para juegos de GBA (y otras consolas 2D)
   Color remasterizado + bordes xBR-lv3 + nitidez CAS + resplandor + textura diagonal.

   Partes de terceros (licencia MIT):
     - xBR-lv3: Copyright (C) 2011-2015 Hyllian - sergiogdb@gmail.com
     - CAS: AMD FidelityFX Contrast Adaptive Sharpening, Copyright (c) AMD
   La textura diagonal está inspirada en el filtro de TV de PCSX2 (reescrita).
*/
'''

# ---------------------------------------------------------------- piezas comunes
GRADE = '''
/* Niveles de VIVO 1-4: vibrance, curva en S, toque cálido, gamma (igual que el lanzador) */
vec4 zhdVivo(float lv) {
	if (lv < 1.5) return vec4(0.15, 0.10, 0.008, 1.00);
	if (lv < 2.5) return vec4(0.30, 0.20, 0.015, 1.02);
	if (lv < 3.5) return vec4(0.45, 0.30, 0.025, 1.04);
	return vec4(0.65, 0.42, 0.035, 1.06);
}

vec3 zhdGrade(vec3 c, float lv) {
	vec4 p = zhdVivo(lv);
	float y = dot(c, vec3(0.2126, 0.7152, 0.0722));
	float sat = max(max(c.r, c.g), c.b) - min(min(c.r, c.g), c.b);
	float warm = p.z * smoothstep(0.05, 0.25, sat);  /* blancos, grises y negros quedan neutros */
	c = clamp(vec3(y) + (c - vec3(y)) * (1.0 + p.x * (1.0 - sat)), 0.0, 1.0);
	vec3 s = c * c * (3.0 - 2.0 * c);
	c = c + (s - c) * p.y;
	c = pow(c, vec3(1.0 / p.w));
	c.r *= 1.0 + warm;
	c.b *= 1.0 - warm;
	return clamp(c, 0.0, 1.0);
}

float zhdSuavizado(float lv) {
	return 0.30 + 0.05 * clamp(floor(lv + 0.5), 1.0, 4.0);  /* 35/40/45/50 % */
}
'''

# CAS + resplandor. SAMPLE(uv) lee la pasada anterior; TS = tamaño de un texel
CAS = '''
vec3 zhdBright(vec3 c) {
	float y = dot(c, vec3(0.2126, 0.7152, 0.0722));
	return c * clamp((y - 0.86) / 0.14, 0.0, 1.0);
}

vec3 zhdCasBloom(vec2 uv, vec2 TS, float nitidez, float brillo) {
	vec3 a = SAMPLE(uv + vec2(-TS.x, -TS.y));
	vec3 b = SAMPLE(uv + vec2(0.0, -TS.y));
	vec3 c = SAMPLE(uv + vec2(TS.x, -TS.y));
	vec3 d = SAMPLE(uv + vec2(-TS.x, 0.0));
	vec3 e = SAMPLE(uv);
	vec3 f = SAMPLE(uv + vec2(TS.x, 0.0));
	vec3 g = SAMPLE(uv + vec2(-TS.x, TS.y));
	vec3 h = SAMPLE(uv + vec2(0.0, TS.y));
	vec3 i = SAMPLE(uv + vec2(TS.x, TS.y));
	vec3 col = e;
	if (nitidez > 0.0) {
		vec3 mn = min(min(min(b, d), min(f, h)), e);
		vec3 mx = max(max(max(b, d), max(f, h)), e);
		vec3 mn2 = min(mn, min(min(a, c), min(g, i)));
		vec3 mx2 = max(mx, max(max(a, c), max(g, i)));
		mn += mn2;
		mx += mx2;
		vec3 amp = clamp(min(mn, 2.0 - mx) / max(mx, vec3(1e-5)), 0.0, 1.0);
		float s = clamp(nitidez / 100.0, 0.0, 1.0);
		vec3 w = sqrt(amp) * (-1.0 / mix(8.0, 5.0, s));
		col = clamp(((b + d + f + h) * w + e) / (1.0 + 4.0 * w), 0.0, 1.0);
	}
	if (brillo > 0.0) {
		/* resplandor: lo más claro, centro + dos anillos (radio 12 y 28 texels de la imagen x4),
		   ajustado para coincidir con el del lanzador */
		vec3 acc = zhdBright(e);
		for (int k = 0; k < 8; ++k) {
			float ang = float(k) * 0.785398;
			vec2 dir = vec2(cos(ang), sin(ang));
			acc += zhdBright(SAMPLE(uv + dir * TS * 12.0));
			acc += zhdBright(SAMPLE(uv + dir * TS * 28.0));
		}
		vec3 bl = acc / 17.0 * (brillo / 100.0);
		col = 1.0 - (1.0 - col) * (1.0 - clamp(bl, 0.0, 1.0));  /* mezcla "pantalla" */
	}
	return col;
}
'''

# Textura diagonal: PX = píxel de pantalla entero
TEX = '''
vec3 zhdTexture(vec3 c, vec2 PX, float textura) {
	float lv = clamp(floor(textura + 0.5), 1.0, 4.0);
	float fuerza = lv < 1.5 ? 0.0 : lv < 2.5 ? 20.0 : lv < 3.5 ? 35.0 : 60.0;
	if (fuerza <= 0.0) return c;
	float lo = 1.0 - fuerza / 200.0;
	float idx = mod(PX.x + mod(PX.y, 3.0), 3.0);
	vec3 m = vec3(lo);
	if (idx < 0.5) m.r = 1.0; else if (idx < 1.5) m.g = 1.0; else m.b = 1.0;
	float add = 1.2 * (1.0 - (1.0 + 2.0 * lo) / 3.0);  /* devuelve la luz que quita la máscara */
	return clamp(c * m + c * add, 0.0, 1.0);
}
'''

# ---------------------------------------------------------------- xBR original
src = open(XBR_FS).read()
lic_end = src.index('*/') + 2
xbr_license = src[:lic_end]
helpers = src[src.index('uniform float XBR_Y_WEIGHT;'):src.index('// GLSL shader autogenerated')]
body = src[src.index('void main()'):]
body = body[body.index('{') + 1:body.rindex('}')]
assert 'FragColor = vec4(res, 1.0);' in body
FINAL = '''res = mix(E, res, zhdSuavizado(ZHD_BORDES));
    FragColor = vec4(zhdGrade(res, ZHD_VIVO), 1.0);'''

def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', newline='\n').write(text)

# ================================================================ mGBA
MG = os.path.join(ROOT, 'mgba', 'zadark-hd.shader')
mg_helpers = helpers.replace('uniform float XBR_LV2_COEFFICIENT;',
                             'uniform float XBR_LV2_COEFFICIENT;\nuniform float ZHD_BORDES;\nuniform float ZHD_VIVO;')
mg_pre = src[src.index('// GLSL shader autogenerated'):src.index('void main()')]
write(os.path.join(MG, 'zhd-xbr.fs'), HEADER + '\n' + xbr_license + '\n\n' + mg_helpers + GRADE + '\n' + mg_pre
      + 'void main()\n{' + body.replace('FragColor = vec4(res, 1.0);', FINAL) + '}\n')
write(os.path.join(MG, 'xbr.vs'), open(XBR_VS).read())

MG_PRE = '''#ifdef GL_ES
#ifdef GL_FRAGMENT_PRECISION_HIGH
precision highp float;
#else
precision mediump float;
#endif
#endif
uniform sampler2D tex;
uniform vec2 texSize;
varying vec2 texCoord;
'''
write(os.path.join(MG, 'zhd-cas.fs'), HEADER + MG_PRE + '''uniform float ZHD_NITIDEZ;
uniform float ZHD_BRILLO;
#define SAMPLE(uv) texture2D(tex, uv).rgb
''' + CAS + '''
void main() {
	/* En mGBA texSize es siempre el tamaño de la GBA; la pasada anterior es x4 */
	vec2 TS = vec2(1.0) / (texSize * 4.0);
	gl_FragColor = vec4(zhdCasBloom(texCoord, TS, ZHD_NITIDEZ, ZHD_BRILLO), 1.0);
}
''')
write(os.path.join(MG, 'zhd-tex.fs'), HEADER + MG_PRE + '''uniform float ZHD_TEXTURA;
''' + TEX + '''
void main() {
	vec3 c = texture2D(tex, texCoord).rgb;
	gl_FragColor = vec4(zhdTexture(c, floor(gl_FragCoord.xy), ZHD_TEXTURA), 1.0);
}
''')

def uni(p, name, label, default, mn, mx):
    return f'''
[pass.{p}.uniform.{name}]
type=float
readableName={label}
default={default}
min={mn}
max={mx}
'''

manifest = '''[shader]
name=Zadark HD
author=Zadark (xBR-lv3: Hyllian, CAS: AMD)
description=Color remasterizado, bordes suaves, nitidez, resplandor y textura de pantalla. Niveles 1-4.
passes=3

[pass.0]
integerScaling=1
width=-4
height=-4
vertexShader=xbr.vs
fragmentShader=zhd-xbr.fs
''' + uni(0, 'ZHD_BORDES', 'Bordes 1-4 (35-50 %)', 2, 1, 4) + uni(0, 'ZHD_VIVO', 'Vivo 1-4 (color)', 3, 1, 4) \
    + uni(0, 'XBR_Y_WEIGHT', 'xBR Y Weight', 48, 0, 100) + uni(0, 'XBR_EQ_THRESHOLD', 'xBR Eq Threshold', 10.0, 0.0, 50.0) \
    + uni(0, 'XBR_EQ_THRESHOLD2', 'xBR Eq Threshold2', 2.0, 0.0, 4.0) + uni(0, 'XBR_LV2_COEFFICIENT', 'xBR Lv2 Coefficient', 2.0, 1.0, 3.0) + '''
[pass.1]
width=-4
height=-4
fragmentShader=zhd-cas.fs
''' + uni(1, 'ZHD_NITIDEZ', 'Nitidez 0-100', 60, 0, 100) + uni(1, 'ZHD_BRILLO', 'Resplandor 0-100', 22, 0, 100) + '''
[pass.2]
filter=1
width=0
height=0
fragmentShader=zhd-tex.fs
''' + uni(2, 'ZHD_TEXTURA', 'Textura 1-4 (1 = sin textura)', 1, 1, 4)
write(os.path.join(MG, 'manifest.ini'), manifest)

# ================================================================ RetroArch (slang)
RA = os.path.join(ROOT, 'retroarch')
PARAMS = {
    'ZHD_BORDES': ('Zadark HD - Bordes (1-4)', 2.0, 1.0, 4.0, 1.0),
    'ZHD_VIVO': ('Zadark HD - Vivo (1-4)', 3.0, 1.0, 4.0, 1.0),
    'ZHD_NITIDEZ': ('Zadark HD - Nitidez (0-100)', 60.0, 0.0, 100.0, 5.0),
    'ZHD_BRILLO': ('Zadark HD - Resplandor (0-100)', 22.0, 0.0, 100.0, 2.0),
    'ZHD_TEXTURA': ('Zadark HD - Textura (1 = sin, 4 = marcada)', 1.0, 1.0, 4.0, 1.0),
    'XBR_Y_WEIGHT': ('xBR Y Weight', 48.0, 0.0, 100.0, 1.0),
    'XBR_EQ_THRESHOLD': ('xBR Eq Threshold', 10.0, 0.0, 50.0, 1.0),
    'XBR_EQ_THRESHOLD2': ('xBR Eq Threshold2', 2.0, 0.0, 4.0, 0.1),
    'XBR_LV2_COEFFICIENT': ('xBR Lv2 Coefficient', 2.0, 1.0, 3.0, 0.1),
}

def slang(params, fragment_globals, fragment_main, extra_vs=''):
    push = ''.join(f'\tfloat {p};\n' for p in params)
    pragmas = ''.join('#pragma parameter %s "%s" %.1f %.1f %.1f %.1f\n' % ((p,) + PARAMS[p]) for p in params)
    defs = ''.join(f'#define {p} params.{p}\n' for p in params)
    return f'''#version 450
{HEADER}
layout(push_constant) uniform Push {{
	vec4 SourceSize;
	vec4 OriginalSize;
	vec4 OutputSize;
	uint FrameCount;
{push}}} params;

{pragmas}{defs}
layout(std140, set = 0, binding = 0) uniform UBO {{
	mat4 MVP;
}} global;

#pragma stage vertex
layout(location = 0) in vec4 Position;
layout(location = 1) in vec2 TexCoord;
layout(location = 0) out vec2 vTexCoord;

void main() {{
	gl_Position = global.MVP * Position;
	vTexCoord = TexCoord;
}}

#pragma stage fragment
layout(location = 0) in vec2 vTexCoord;
layout(location = 0) out vec4 FragColor;
layout(set = 0, binding = 2) uniform sampler2D Source;
{fragment_globals}
void main() {{
{fragment_main}}}
'''

# xBR en slang: las coordenadas que mGBA calcula en el vértice se calculan aquí
ra_helpers = re.sub(r'uniform float (XBR_\w+);\n', '', helpers)
ra_body = body.replace('FragColor = vec4(res, 1.0);', FINAL).replace('COMPAT_TEXTURE(tex,', 'texture(Source,')
ra_body = ra_body.replace('vec2 fp = fract(texCoord * texSize);', '''vec2 texSize = params.SourceSize.xy;
	vec2 texCoord = vTexCoord;
	float dx = params.SourceSize.z;
	float dy = params.SourceSize.w;
	vec4 TEX1 = texCoord.xxxy + vec4( -dx, 0, dx,-2.0*dy); // A1 B1 C1
	vec4 TEX2 = texCoord.xxxy + vec4( -dx, 0, dx,    -dy); //  A  B  C
	vec4 TEX3 = texCoord.xxxy + vec4( -dx, 0, dx,      0); //  D  E  F
	vec4 TEX4 = texCoord.xxxy + vec4( -dx, 0, dx,     dy); //  G  H  I
	vec4 TEX5 = texCoord.xxxy + vec4( -dx, 0, dx, 2.0*dy); // G5 H5 I5
	vec4 TEX6 = texCoord.xyyy + vec4(-2.0*dx,-dy, 0,  dy); // A0 D0 G0
	vec4 TEX7 = texCoord.xyyy + vec4( 2.0*dx,-dy, 0,  dy); // C4 F4 I4
	vec2 fp = fract(texCoord * texSize);''')
assert 'texture(Source,' in ra_body and 'vec4 TEX7' in ra_body
xbr_params = ['ZHD_BORDES', 'ZHD_VIVO', 'XBR_Y_WEIGHT', 'XBR_EQ_THRESHOLD', 'XBR_EQ_THRESHOLD2', 'XBR_LV2_COEFFICIENT']
write(os.path.join(RA, 'zadark-hd', 'zhd-xbr.slang'),
      slang(xbr_params, '\n' + xbr_license + '\n' + ra_helpers + GRADE, ra_body))
write(os.path.join(RA, 'zadark-hd', 'zhd-cas.slang'),
      slang(['ZHD_NITIDEZ', 'ZHD_BRILLO'], '#define SAMPLE(uv) texture(Source, uv).rgb\n' + CAS,
            '\tFragColor = vec4(zhdCasBloom(vTexCoord, params.SourceSize.zw, ZHD_NITIDEZ, ZHD_BRILLO), 1.0);\n'))
write(os.path.join(RA, 'zadark-hd', 'zhd-tex.slang'),
      slang(['ZHD_TEXTURA'], TEX,
            '\tvec3 c = texture(Source, vTexCoord).rgb;\n'
            '\tFragColor = vec4(zhdTexture(c, floor(vTexCoord * params.OutputSize.xy), ZHD_TEXTURA), 1.0);\n'))
write(os.path.join(RA, 'zadark-hd.slangp'), '''shaders = 3

shader0 = zadark-hd/zhd-xbr.slang
filter_linear0 = false
scale_type0 = source
scale0 = 4.0

shader1 = zadark-hd/zhd-cas.slang
filter_linear1 = false
scale_type1 = source
scale1 = 1.0

shader2 = zadark-hd/zhd-tex.slang
filter_linear2 = true
scale_type2 = viewport
scale2 = 1.0
''')
print('Generado en', ROOT)
