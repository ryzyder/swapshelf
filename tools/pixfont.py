# filas 0-1 acentos de mayúsculas, 2-8 cuerpo (mayúsculas 7 filas), 9-10 descendentes.
# Minúsculas: altura x en filas 4-8. '#' = tinta.
G = {}

def g(ch, rows, top=2):
    rows = rows.strip('\n').split('\n')
    w = max(len(r) for r in rows)
    grid = [[0] * w for _ in range(11)]
    for i, r in enumerate(rows):
        for j, c in enumerate(r):
            if c == '#':
                grid[top + i][j] = 1
    G[ch] = grid

