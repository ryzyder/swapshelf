# Acentos: se copia la letra base y se dibuja el acento encima
def accented(ch, base, mark):
    b = [row[:] for row in G[base]]
    w = len(b[0])
    top = 2 if base.islower() else 0
    if base in 'il':
        top = 2  # sin punto
        b[2] = [0] * w
    if mark == 'acute':
        x = min(w - 1, w // 2 + 1) if w > 2 else w - 1
        b[top][x] = 1
        if w > 2: b[top + 1][x - 1] = 1
    elif mark == 'tilde':
        pat = [0, 1, 0, 1][:w] if w >= 4 else [1] * w
        row1 = [1, 0, 1, 0, 0][:w]
        for j in range(w):
            b[top][j] = 1 if j in (1, 2) and w >= 4 else 0
        b[top][0] = 0
        b[top][1:3] = [1, 0] if w >= 4 else b[top][1:3]
        # tilde: .#.# / #.#.
        b[top] = [1 if j in (1, 3) else 0 for j in range(w)]
        b[top + 1] = [1 if j in (0, 2) else 0 for j in range(w)]
    elif mark == 'grave':
        x = max(0, w // 2 - 1) if w > 2 else 0
        b[top][x] = 1
        if w > 2: b[top + 1][x + 1] = 1
    elif mark == 'circ':
        c = w // 2 if w % 2 else w // 2 - (1 if w > 3 else 0)
        b[top] = [1 if j == c or (w % 2 == 0 and j == c + 1) else 0 for j in range(w)]
        b[top + 1] = [1 if j in (max(0, c - 1), min(w - 1, c + (2 if w % 2 == 0 else 1))) else 0 for j in range(w)]
    elif mark == 'cedilla':
        x = w // 2
        b[9][x] = 1
        b[10][max(0, x - 1)] = 1
    elif mark == 'diaer':
        b[top + 1] = [1 if j in (0, w - 1) else 0 for j in range(w)]
    G[ch] = b

